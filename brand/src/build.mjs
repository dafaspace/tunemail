// Writes every SVG of the Tunemail mark from tunemail.js - the only source of the geometry.
// Never edit an SVG by hand: change tunemail.js and run this again.
//   node brand/src/build.mjs        then        <python with Pillow+numpy> brand/src/render.py
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { tunemail, COL } from './tunemail.js'

const here = path.dirname(fileURLToPath(import.meta.url))
const out = path.join(here, '..', 'svg')
fs.mkdirSync(path.join(out, 'layers'), { recursive: true })
fs.mkdirSync(path.join(out, '..', 'web'), { recursive: true })

const svg = (inner, head = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">${head}${inner}</svg>\n`

// The app icon: the mark at 92.1 %, so the envelope spans x 215-810 - where Cinemail's icon (shipped
// in v0.55) has it, so the two icons match - on the ink ground, square and opaque (the stores round the corners).
export const ICON = 0.921
const k = ICON, d = +(512 * (1 - k)).toFixed(2)
const inIcon = inner => `<g transform="translate(${d} ${d}) scale(${k})">${inner}</g>`
const ground = `<rect width="1024" height="1024" fill="${COL.ink}"/>`

// the record turns about its spindle: rotate the element with class "spin"
const spinCss = '<style>.spin{animation:spin 8s linear infinite;transform-box:fill-box;transform-origin:center}' +
  '@keyframes spin{to{transform:rotate(360deg)}}@media (prefers-reduced-motion:reduce){.spin{animation:none}}</style>'

const files = {
  'tunemail-mark.svg': svg(tunemail({ bare: true })),
  'tunemail-mark-ink.svg': svg(tunemail({ bare: true, variant: 'ink' })),
  'tunemail-mark-spin.svg': svg(tunemail({ bare: true }), spinCss),
  'tunemail-icon.svg': svg(ground + inIcon(tunemail({ bare: true }))),
  // Icon Composer layers, in icon position. Every part is already cut free of the parts in
  // front of it, so the layers never overlap and their order cannot change the picture.
  'layers/1-background.svg': svg(ground),
  'layers/2-envelope.svg': svg(inIcon(tunemail({ bare: true, only: ['back', 'flap', 'bottom', 'right', 'left'] }))),
  'layers/3-record.svg': svg(inIcon(tunemail({ bare: true, only: ['record'] }))),
}
// The logo where it can be tapped, inline so the record can turn. The same behaviour as
// Cinemail's: a pop and a full turn, on first show and on every tap. Give each copy on a page
// its own id prefix (the second argument of inline()), because two masks with one id would
// draw one copy with the other's mask.
const inline = prefix => tunemail({ bare: true }).replace(/\bt\d+-/g, prefix + '-')
files['../web/logo-tap.html'] = `<!-- The tappable Tunemail logo: a pop and a full turn of the record, on first show and on
     every tap. Generated by brand/src/build.mjs from tunemail.js - do not edit by hand.
     The CSS and the JS go in once, the <svg> wherever the logo is; size it with width/height. -->

<svg class="logo-tap pop" viewBox="0 0 1024 1024" role="img" aria-label="Tunemail" onclick="_bounceLogo(this)" style="width:96px;height:96px;cursor:pointer;-webkit-tap-highlight-color:transparent">${inline('tl')}</svg>

<!-- CSS, once. The record's gap and its ink edge sit in masks; they carry class "spin" too, so
     the same rule turns them with the record and the gap keeps its width all the way round. -->
<style>
@keyframes logo-pop {
  0%   { transform: scale(1)    rotate(0deg); }
  20%  { transform: scale(1.18) rotate(-7deg); }
  45%  { transform: scale(0.93) rotate(5deg); }
  70%  { transform: scale(1.06) rotate(-2deg); }
  100% { transform: scale(1)    rotate(0deg); }
}
.logo-tap.pop { animation: logo-pop .6s cubic-bezier(.34,1.56,.64,1); }
.logo-tap .spin { transform-box: fill-box; transform-origin: center; }
.logo-tap.pop .spin { animation: record-turn 1.1s cubic-bezier(.2,.7,.2,1); }
@keyframes record-turn { to { transform: rotate(360deg); } }
@media (prefers-reduced-motion: reduce) { .logo-tap.pop, .logo-tap.pop .spin { animation: none; } }
</style>

<!-- JS, once. getBoundingClientRect() forces the restart; on an <svg> offsetWidth is undefined. -->
<script>
function _bounceLogo(el) {
  el.classList.remove('pop');
  void el.getBoundingClientRect();
  el.classList.add('pop');
}
</script>
`
for (const [name, body] of Object.entries(files)) {
  fs.writeFileSync(path.join(out, name), body)
  console.log(`${name}  ${(body.length / 1024).toFixed(1)} KB`)
}
